"""genllr.py OUT.S: ARC600 kernels of the new renderer (s9x/src/llr.c, -DLL_NEWR). No lp loops, no gp.

llr_bg_fF / llr_bg8_fF (args r0), F = fine x scroll 0..7: one run of one BG layer (8x8 tiles, no window;
bg: 2/4 bpp from the nibble tile cache, 32 bytes per tile, pixel x = nibble x; bg8: 8 bpp from snes9x's
tile cache, 64 bytes per tile, pixel x = byte x), tiles of one priority. A run is up to 16 line buffers
whose lines are on the same map row: per tile the map entry is read once and the tile's row is drawn
into each line buffer (tile strip). Line buffers hold only the 160 shown columns (x mod 8 in 0,1,3,4,6);
tile k's 5-column group starts at lb + 5k. Returns 0 when done, or 1 with args.k = a tile whose cache
entry isn't converted yet (TileCached = 0: the caller converts it and calls again, the kernel restarts
at tile k). Tiles marked BLANK_TILE (2) are skipped.
args (struct llr_k): 0 map a, 4 count a, 8 map b, 12 count b, 16 tile cache, 20 cached flags, 24 nbase,
28 tmask, 32 palstart, 36 palsh, 40 palmask, 44 prio (0 / 0x2000), 48 nrows, 52 k, 56 lb[16],
120 ro[16] (row offset in a tile: row*4, 8 bpp row*8), 184 rv[16] (the same for 7-row, v-flip).

llr_out12(dst r0, lb r1, pal r2, palb r3) / llr_out12di (st.di): 160 CG indices -> 240 bytes of 12 bpp.
llr_copy240di(dst r0, src r1): 60 words with st.di."""
