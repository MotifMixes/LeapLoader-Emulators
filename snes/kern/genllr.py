# ---- llr_objpx(b r0, w r1, pal r2, sel r3) (llr.c -DLLR_OBJASM): one sprite tile row, sel = fine | hflip << 3;
# pixel p (nibble p of w, 0 = transparent) -> b[offset] = pal + p, as llr_obj_row's loop without mask/priority
out += ['\t.section .rodata', '\t.align 4', '.Lobjtab:'] + [f'\t.word .Lop{s}' for s in range(16)] + ['\t.text']
