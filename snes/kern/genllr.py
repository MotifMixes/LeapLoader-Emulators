def pixels(fine, flip):
    """(tile pixel, line buffer offset from 5k) of the shown pixels of a tile at fine scroll `fine`"""
    r = []
    for i in range(8):
        x = i - fine
        g, c = divmod(x, 8)
        if c in COL:
            r.append((7 - i if flip else i, g * 5 + COL[c]))
    return sorted(r)


def emit_pixels(px, lbl, b8):
    # pixel p: nibble p of r19 (2/4 bpp), or byte p of r19 (p < 4) / r25 (8 bpp); 0 = transparent,
    # else pal (r15) + value stored at r20 + offset
    o = []
    for n, (p, off) in enumerate(px):
        if b8:
            w, sh, m = ('r19' if p < 4 else 'r25'), 8 * (p & 3), 255
        else:
            w, sh, m = 'r19', 4 * p, 15
        if sh == 0:
            o.append(f'\tand.f\tr21,{w},{m}')
        else:
            o.append(f'\tlsr\tr21,{w},{sh}')
            o.append(f'\tand.f\tr21,r21,{m}')
        o.append(f'\tbeq.d\t{lbl}{n}')
        o.append('\tadd\tr21,r21,r15')
        o.append(f'\tstb\tr21,[r20,{off}]')
        o.append(f'{lbl}{n}:')
    return o


