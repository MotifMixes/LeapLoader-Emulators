# llr_out12di2 (-DLLR_OUT2, same arguments as llr_out12di): the st.di of group g-1's three words spread
# through group g's conversion (one every ~12 cycles) instead of three back to back: with a posted store
# queue of depth 1 the burst made the CPU wait twice per group; spread, the loop runs at the VRAM bus rate
def out12di2(z=0, name='llr_out12di2'):
    ld = [f'	ldb	r{4 + j},[r1,{j}]' for j in range(8)]
    lk = [f'	ldw.as	r{4 + j},[r2,r{4 + j}]' if j % 2 == 0 else f'	ld.as	r{4 + j},[r3,r{4 + j}]' for j in range(8)]
    cb = ['	or	r4,r4,r5', '	or	r6,r6,r7', '	or	r8,r8,r9', '	or	r10,r10,r11',
          '	asl	r15,r6,24', '	or	r15,r15,r4', '	lsr	r16,r6,8', '	asl	r5,r8,16', '	or	r16,r16,r5',
          '	lsr	r17,r8,16', '	asl	r9,r10,8', '	or	r17,r17,r9']
    # z (-DLLR_OUTZ): the line buffer is cleared behind the conversion (two cached stores per group, free
    # while the loop waits for the VRAM bus), so llr_part skips the next chunk's memset of it
    zs = ['	st	0,[r1,0]', '	st	0,[r1,4]'] if z else []
    L = f'.L{name}'
    o = [f'	.global {name}', '	.align 4', f'{name}:', '	sub	sp,sp,12',
         '	st	r15,[sp,0]', '	st	r16,[sp,4]', '	st	r17,[sp,8]', '	mov	r12,19']
    o += ld + zs + lk + cb + ['	add	r1,r1,8', '	add	r0,r0,12', f'{L}:']
    body = ['	st.di	r15,[r0,-12]'] + ld[:6] + ['	st.di	r16,[r0,-8]'] + ld[6:] + zs + lk[:6] +            ['	st.di	r17,[r0,-4]'] + lk[6:] + cb
    o += body + ['	add	r1,r1,8', '	sub.f	r12,r12,1', f'	bne.d	{L}', '	add	r0,r0,12']
    o += ['	st.di	r15,[r0,-12]', '	st.di	r16,[r0,-8]', '	st.di	r17,[r0,-4]',
          '	ld	r15,[sp,0]', '	ld	r16,[sp,4]', '	ld	r17,[sp,8]', '	j.d	[blink]', '	add	sp,sp,12']
    return o
