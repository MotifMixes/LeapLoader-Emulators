"""genfxtab.py: s9x/src/fxjit_tab.h, the GSU translator's view of fxinst.c's opcode table (1024 entries,
ALT0-ALT3): one byte kind (K_<name>) + one byte operand (register or immediate) per entry.
genfxtab.py [FXINST.C [OUT.H]] (default: s9x/src/fxinst.c -> s9x/src/fxjit_tab.h)."""
import re, sys
s = open(sys.argv[1] if len(sys.argv) > 1 else 's9x/src/fxinst.c').read()
i = s.index('void (*fx_apfOpcodeTable[])() =')
names = re.findall(r'&(fx_\w+)', s[i:s.index('};', i)])
assert len(names) == 1024
kinds, ent = [], []
for n in names:
    m = re.match(r'fx_(\w+?)(?:_(r|i)(\d+))?$', n)
    k = m.group(1) + ('_' + m.group(2) if m.group(2) else '')
    k = {'plot_2bit': 'plot', 'rpix_2bit': 'rpix'}.get(k, k)
    if k not in kinds: kinds.append(k)
    ent.append((k, int(m.group(3) or 0)))
o = ['/* generated by kern/genfxtab.py from fxinst.c: do not edit */', 'enum {']
o += ['  K_%s,' % k.upper() for k in kinds] + ['  K_NKINDS };',
      'static const unsigned char fxj_tab[1024][2] = {']
o += ['  {K_%s, %d},' % (k.upper(), n) for k, n in ent] + ['};']
open(sys.argv[2] if len(sys.argv) > 2 else 's9x/src/fxjit_tab.h', 'w', newline='\n').write('\n'.join(o) + '\n')
print(len(kinds), 'kinds')
