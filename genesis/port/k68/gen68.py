# gen68.py: generates k68i.S, the hand-designed ARC600 68000 interpreter
# (-DK68). The instruction semantics are written here as ARC600 assembly
# templates; FAME (fametab.py) supplies the cycle counts, so that the core
# charges exactly what PicoDrive's FAME would.
#
# Register use (ARC600, no lp, no gp):
#  r13 &ctx->dreg[0] (D0-D7, then A0-A7; ctx fields at OFS_*)
#  r19 &ctx->areg[0]   r14 PC (host u16 *)   r15 BasePC (PC - r15 = 68k PC)
#  r16 cycles left     r17 opcode            r18 &k68_table (handler per op>>3)
#  r20 N/Z source: Z = (r20 == 0), N = bit 31 (or r22 bit 3 when r20 == 0)
#  r22 CCR bits X (4), N (3, only with r20 == 0), V (1), C (0); bit 2 is 0
#  r21 r23 r24 r25: temporaries kept across memory calls (as r4-r12)
# Memory: bl k68_rd8/16/32 (r0 addr -> r0), bl k68_wr8/16/32 (r0 addr, r1
# data) clobber only r0-r3 and blink; I/O goes to PicoDrive's map handlers.
import sys, re, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fametab

T = fametab.jumptable()
H = fametab.handlers()

OFS = dict(asp=0x40, pc=0x44, interrupts=0x48, sr=0x50, execinfo=0x52, cnt=0x54, opcode=0x58,
           cneed=0x5c, PC=0x60, BasePC=0x64, fC=0x68, fV=0x6c, fNotZ=0x70, fN=0x74, fX=0x78,
           fT=0x7c, fS=0x80, fI=0x84, Fetch=0x8c)


def fame_cycles(op):
    """cycles of FAME's handler for op when it has one constant RET and no
    other counter change, else None"""
    h = T[op]
    body = '\n'.join(H[h])
    r = set(fametab.rets(H[h]))
    if len(r) != 1 or 'io_cycle_counter' in body: return None
    v = r.pop()
    if not re.fullmatch(r'[0-9+\- ]+', v): return None
    return eval(v)

out = []
def emit(s): out.append(s)

# ---------------------------------------------------------------- framework
FRAME = r'''
; k68i.S: generated by gen68.py - do not edit
	.text
	.global k68_exec
	.global k68_done
	.global k68_fallback
	.global k68_is_fallback
	.global k68_flags_out
	.global k68_flags_in

; NEXT cyc: charge the cycles, fetch and dispatch the next opcode
.macro NEXT cyc
#ifdef K68CHECK
	sub	r16,r16,\cyc
	b	k68_done
#else
	ldw	r17,[r14]
	sub.f	r16,r16,\cyc
	ble	k68_done
	lsr	r1,r17,3
	ld.as	r1,[r18,r1]
	add	r14,r14,2
	j	[r1]
#endif
.endm

; NEXTR reg: the same with the cycle count in a register
.macro NEXTR reg
#ifdef K68CHECK
	sub	r16,r16,\reg
	b	k68_done
#else
	ldw	r17,[r14]
	sub.f	r16,r16,\reg
	ble	k68_done
	lsr	r1,r17,3
	ld.as	r1,[r18,r1]
	add	r14,r14,2
	j	[r1]
#endif
.endm

; FAME's WRITE_LONG_DEC_F (long writes to -(An)): low word first
	.align 4
k68_wr32d:
	sub	sp,sp,12
	st	blink,[sp,0]
	st	r0,[sp,4]
	st	r1,[sp,8]
	bl.d	k68_wr16
	add	r0,r0,2
	ld	r0,[sp,4]
	ld	r1,[sp,8]
	bl.d	k68_wr16
	lsr	r1,r1,16
	ld	blink,[sp,0]
	j.d	[blink]
	add	sp,sp,12

; branch to an odd address (r14/r15 set): FAME's CHECK_BRANCH_EXCEPTION -
; address error exception, then the time slice ends (counter = 0)
k68_addrerr:
	st	r14,[r13,0x60]
	st	r15,[r13,0x64]
	st	r16,[r13,0x54]
	bl	k68_flags_out
	bl.d	k68_addr_error
	sub	r0,r13,0x20
	ld	r14,[r13,0x60]
	ld	r15,[r13,0x64]
	bl	k68_flags_in
	b.d	k68_done
	mov	r16,0

; exception from an instruction: r0 vector, r1 old PC (68k). Flags and PC
; synced around k68_exception (k68c.c), which also charges the cycles.
k68_exc:
	st	blink,[sp,-4]
	sub	sp,sp,4
	st	r14,[r13,0x60]
	st	r15,[r13,0x64]
	st	r16,[r13,0x54]
	mov	r4,r0
	mov	r5,r1
	bl	k68_flags_out
	sub	r0,r13,0x20
	mov	r1,r4
	bl.d	k68_exception
	mov	r2,r5
	ld	r14,[r13,0x60]
	ld	r15,[r13,0x64]
	ld	r16,[r13,0x54]
	bl	k68_flags_in
	ld	blink,[sp,0]
	j.d	[blink]
	add	sp,sp,4

; ---- status register: r0 <- SR (FAME's GET_SR); clobbers r1
k68_getsr:
	and	r0,r22,0x1b
	brne	r20,0,1f
	or	r0,r0,4
1:	brge	r20,0,2f
	or	r0,r0,8
2:	ld	r1,[r13,0x84]
	asl	r1,r1,8
	or	r0,r0,r1
	ld	r1,[r13,0x80]
	or	r0,r0,r1
	ld	r1,[r13,0x7c]
	j.d	[blink]
	or	r0,r0,r1

; CCR <- r0 (FAME's SET_CCR: bits 0-4); clobbers r1, keeps r0
k68_setccr:
	and	r22,r0,0x13
	bbit1	r0,2,1f
	mov	r20,1
	bbit0	r0,3,2f
	mov	r20,0x80000001
2:	j	[blink]
1:	mov	r20,0
	and	r1,r0,8
	j.d	[blink]
	or	r22,r22,r1

; SR <- r0 (FAME's SET_SR: CCR, T, S, I); clobbers r1, r3
k68_setsr:
	mov	r3,blink
	bl	k68_setccr
	and	r1,r0,0x8000
	st	r1,[r13,0x7c]
	and	r1,r0,0x2000
	st	r1,[r13,0x80]
	lsr	r1,r0,8
	and	r1,r1,7
	j.d	[r3]
	st	r1,[r13,0x84]

; user mode now (flag_S clear): swap A7 and the other stack pointer; clobbers r1, r2
k68_swapusp:
	ld	r1,[r13,0x80]
	brne	r1,0,1f
	ld	r1,[r19,28]
	ld	r2,[r13,0x40]
	st	r2,[r19,28]
	st	r1,[r13,0x40]
1:	j	[blink]

; void k68_exec(M68K_CONTEXT *ctx): runs at least one instruction, until the
; cycle counter is <= 0. ctx->PC/BasePC/flag_* in, out.
	.align 4
k68_exec:
	sub	sp,sp,64
	st	blink,[sp,0]
	st	r13,[sp,4]
	st	r14,[sp,8]
	st	r15,[sp,12]
	st	r16,[sp,16]
	st	r17,[sp,20]
	st	r18,[sp,24]
	st	r19,[sp,28]
	st	r20,[sp,32]
	st	r21,[sp,36]
	st	r22,[sp,40]
	st	r23,[sp,44]
	st	r24,[sp,48]
	st	r25,[sp,52]
	add	r13,r0,0x20
	add	r19,r0,0x40
	ld	r14,[r13,0x60]
	ld	r15,[r13,0x64]
	ld	r16,[r13,0x54]
	mov	r18,k68_table
	bl	k68_flags_in
#ifdef K68JIT
	b	k68_dispatch
#endif
	ldw	r17,[r14]
	lsr	r1,r17,3
	ld.as	r1,[r18,r1]
	add	r14,r14,2
	j	[r1]

k68_done:
	st	r14,[r13,0x60]
	st	r15,[r13,0x64]
	st	r16,[r13,0x54]
	bl	k68_flags_out
	ld	blink,[sp,0]
	ld	r13,[sp,4]
	ld	r14,[sp,8]
	ld	r15,[sp,12]
	ld	r16,[sp,16]
	ld	r17,[sp,20]
	ld	r18,[sp,24]
	ld	r19,[sp,28]
	ld	r20,[sp,32]
	ld	r21,[sp,36]
	ld	r22,[sp,40]
	ld	r23,[sp,44]
	ld	r24,[sp,48]
	ld	r25,[sp,52]
	j.d	[blink]
	add	sp,sp,64

; flags: r20/r22 -> FAME's ctx->flag_C/V/NotZ/N/X (clobbers r0, r1)
k68_flags_out:
	and	r0,r22,1
	asl	r0,r0,8
	st	r0,[r13,0x68]
	and	r0,r22,2
	asl	r0,r0,6
	st	r0,[r13,0x6c]
	st	r20,[r13,0x70]
	lsr	r0,r20,31
	lsr	r1,r22,3
	or	r0,r0,r1
	and	r0,r0,1
	asl	r0,r0,7
	st	r0,[r13,0x74]
	and	r0,r22,0x10
	asl	r0,r0,4
	j.d	[blink]
	st	r0,[r13,0x78]

; flags: FAME's ctx->flag_* -> r20/r22 (clobbers r0-r2)
k68_flags_in:
	ld	r2,[r13,0x68]
	ld	r1,[r13,0x6c]
	ld	r0,[r13,0x78]
	lsr	r2,r2,8
	and	r22,r2,1
	lsr	r1,r1,6
	and	r1,r1,2
	or	r22,r22,r1
	lsr	r0,r0,4
	and	r0,r0,0x10
	or	r22,r22,r0
	ld	r0,[r13,0x70]
	ld	r1,[r13,0x74]
	lsr	r1,r1,7
	and	r1,r1,1
	breq	r0,0,1f
	asl	r20,r1,31
	j.d	[blink]
	or	r20,r20,1
1:	mov	r20,0
	asl	r1,r1,3
	j.d	[blink]
	or	r22,r22,r1

; any opcode not done here: FAME's handler (exact by construction)
	.align 4
k68_fallback:
	st	r14,[r13,0x60]
	st	r15,[r13,0x64]
	st	r16,[r13,0x54]
	st	r17,[r13,0x58]
	bl	k68_flags_out
	ld	r1,[k68_fallbacks]
	add	r1,r1,1
	st	r1,[k68_fallbacks]
#ifdef K68STATS
	add2	r1,k68_fbcount,r17
	ld	r0,[r1]
	add	r0,r0,1
	st	r0,[r1]
#endif
	ld	r1,[k68_fametab]
	ld.as	r1,[r1,r17]
	jl.d	[r1]
	sub	r0,r13,0x20
	ld	r14,[r13,0x60]
	ld	r15,[r13,0x64]
	ld	r16,[r13,0x54]
	bl	k68_flags_in
	NEXT	0

; int k68_is_fallback(unsigned op)
k68_is_fallback:
	lsr	r0,r0,3
	add2	r0,k68_table,r0
	ld	r0,[r0]
	mov	r1,k68_fallback
	sub.f	0,r0,r1
	mov	r0,0
	j.d	[blink]
	mov.eq	r0,1
'''

# memory access routines
MEM_FAST = r'''
; ---- memory: r0 = 68k address (r1 = data for writes); result in r0.
; Clobber r0-r3 (and blink). PicoDrive's maps: entry v, MSB set -> handler
; at v << 1, else host address (v << 1) + a (16-bit words stored native).
	.align 4
k68_rd8:
	lsr	r2,r0,16
	bmsk	r2,r2,7
	add2	r2,m68k_read8_map,r2
	ld	r2,[r2]
	bmsk	r0,r0,23
	tst	r2,r2
	bmi	k68_slow_r8
	asl	r2,r2,1
	xor	r0,r0,1
	j.d	[blink]
	ldb	r0,[r2,r0]

	.align 4
k68_rd16:
	lsr	r2,r0,16
	bmsk	r2,r2,7
	add2	r2,m68k_read16_map,r2
	ld	r2,[r2]
	and	r0,r0,0xfffffe
	tst	r2,r2
	bmi	k68_slow_r16
	asl	r2,r2,1
	j.d	[blink]
	ldw	r0,[r2,r0]

	.align 4
k68_rd32:
	lsr	r2,r0,16
	bmsk	r2,r2,7
	add2	r2,m68k_read16_map,r2
	ld	r2,[r2]
	and	r0,r0,0xfffffe
	tst	r2,r2
	bmi	k68_slow_r32
	asl	r2,r2,1
	add	r2,r2,r0
	ldw	r3,[r2,0]
	ldw	r0,[r2,2]
	asl	r3,r3,16
	j.d	[blink]
	or	r0,r0,r3

	.align 4
k68_wr8:
	lsr	r2,r0,16
	bmsk	r2,r2,7
	add2	r2,m68k_write8_map,r2
	ld	r2,[r2]
	bmsk	r0,r0,23
	tst	r2,r2
	bmi	k68_slow_w8
	asl	r2,r2,1
	xor	r0,r0,1
	add	r2,r2,r0
	j.d	[blink]
	stb	r1,[r2]

	.align 4
k68_wr16:
	lsr	r2,r0,16
	bmsk	r2,r2,7
	add2	r2,m68k_write16_map,r2
	ld	r2,[r2]
	and	r0,r0,0xfffffe
	tst	r2,r2
	bmi	k68_slow_w16
	asl	r2,r2,1
	add	r2,r2,r0
	j.d	[blink]
	stw	r1,[r2]

	.align 4
k68_wr32:
	lsr	r2,r0,16
	bmsk	r2,r2,7
	add2	r2,m68k_write16_map,r2
	ld	r2,[r2]
	and	r0,r0,0xfffffe
	tst	r2,r2
	bmi	k68_slow_w32
	asl	r2,r2,1
	add	r2,r2,r0
	lsr	r3,r1,16
	stw	r3,[r2,0]
	j.d	[blink]
	stw	r1,[r2,2]

; slow paths: a C handler; r4-r12 and blink saved, the cycle counter is
; stored for the handler (SekCyclesDone, SekCyclesBurnRun) and reloaded.
.macro SAVE
	sub	sp,sp,56
	st	blink,[sp,0]
	st	r4,[sp,4]
	st	r5,[sp,8]
	st	r6,[sp,12]
	st	r7,[sp,16]
	st	r8,[sp,20]
	st	r9,[sp,24]
	st	r10,[sp,28]
	st	r11,[sp,32]
	st	r12,[sp,36]
	st	r16,[r13,0x54]
.endm
.macro RESTORE
	ld	r16,[r13,0x54]
	ld	blink,[sp,0]
	ld	r4,[sp,4]
	ld	r5,[sp,8]
	ld	r6,[sp,12]
	ld	r7,[sp,16]
	ld	r8,[sp,20]
	ld	r9,[sp,24]
	ld	r10,[sp,28]
	ld	r11,[sp,32]
	ld	r12,[sp,36]
	j.d	[blink]
	add	sp,sp,56
.endm

k68_slow_r8:
	SAVE
	asl	r2,r2,1
	jl	[r2]
	extb	r0,r0
	RESTORE

k68_slow_r16:
	SAVE
	asl	r2,r2,1
	jl	[r2]
	extw	r0,r0
	RESTORE

k68_slow_r32:
	SAVE
	st	r0,[sp,40]
	asl	r2,r2,1
	st	r2,[sp,44]
	jl	[r2]
	asl	r1,r0,16
	ld	r0,[sp,40]
	ld	r2,[sp,44]
	add	r0,r0,2
	jl.d	[r2]
	st	r1,[sp,40]
	ld	r1,[sp,40]
	or	r0,r0,r1
	RESTORE

k68_slow_w8:
	SAVE
	asl	r2,r2,1
	jl.d	[r2]
	extb	r1,r1
	RESTORE

k68_slow_w16:
	SAVE
	asl	r2,r2,1
	jl.d	[r2]
	extw	r1,r1
	RESTORE

k68_slow_w32:
	SAVE
	asl	r2,r2,1
	st	r2,[sp,44]
	st	r0,[sp,40]
	st	r1,[sp,48]
	jl.d	[r2]
	lsr	r1,r1,16
	ld	r0,[sp,40]
	ld	r1,[sp,48]
	ld	r2,[sp,44]
	jl.d	[r2]
	add	r0,r0,2
	RESTORE
'''

def gen_frame():
    emit(FRAME)
    emit('#ifndef K68CHECK')
    emit(MEM_FAST)
    emit('#else\n; check build: every access goes through k68chk_* (k68c.c), which logs it')
    emit(MEM_FAST[MEM_FAST.index('.macro SAVE'):MEM_FAST.index('k68_slow_r8:')])
    for n, f in (('rd8', 'k68chk_r8'), ('rd16', 'k68chk_r16'), ('rd32', 'k68chk_r32'),
                 ('wr8', 'k68chk_w8'), ('wr16', 'k68chk_w16'), ('wr32', 'k68chk_w32')):
        emit('\t.align 4\nk68_%s:\n\tSAVE\n\tbl\t%s\n\tRESTORE' % (n, f))
    emit('#endif')

# ---------------------------------------------------------------- handlers
table = ['k68_fallback'] * 8192
handlers = {}          # asm text -> label (dedupe)

def add_handler(grp, text):
    if text not in handlers:
        handlers[text] = 'h_%04x' % (grp << 3)
    table[grp] = handlers[text]

def gen_handlers():
    import fam68, ops68
    outn = int(os.environ.get('K68OUT') or -1)
    if outn >= 0:   # -DK68OUT: pass 1 (no outlining) gives each group's handler label and rank
        t1 = list(table)
        hs1, _ = fam68.gen(t1)
        hf = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.environ.get('K68HOTF') or 'hot.txt')
        rank = {l.strip(): i for i, l in enumerate(open(hf)) if l.strip()}
        ops68.OUTLINE_GRPS.update(gr for gr in range(8192) if t1[gr] != 'k68_fallback' and rank.get(t1[gr], 1 << 30) >= outn)
        ops68.handlers.clear(); ops68.labels.clear(); ops68.templates.clear(); ops68.ttab.clear(); del ops68.fails[:]
    hs, fails = fam68.gen(table)
    for t, lab in hs.items():
        handlers[t] = lab
    if fails:
        open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'k68fails.txt'), 'w').write('\n'.join(fails) + '\n')
        print(len(fails), 'groups not generated (k68fails.txt)')

JIT = r'''
; ---------------------------------------------------------------- recompiler
#define K68_JTMASK 0x3fff
; Blocks (k68j.c) are copies of the templates below, each preceded by
; "mov r17,opcode / add r14,r14,2"; a template ends in TNEXT: charge the
; cycles and leave when the slice is over (r14 is exact there), as NEXT does.
.macro TNEXT cyc
#ifdef K68CHECK
	sub	r16,r16,\cyc
	j	k68_done
#else
	sub.f	r16,r16,\cyc
	j.le	k68_done
#endif
	b	99f
.endm
.macro TNEXTL cyc		; (the template's last one)
#ifdef K68CHECK
	sub	r16,r16,\cyc
	j	k68_done
#else
	sub.f	r16,r16,\cyc
	j.le	k68_done
#endif
.endm
.macro TNEXTS cyc		; (in the subroutine copy)
#ifdef K68CHECK
	sub	r16,r16,\cyc
	j	k68_done
#else
	sub.f	r16,r16,\cyc
	j.le	k68_done
	j	[r23]
#endif
.endm

; r14 = host address of the next opcode: find its block, or translate
	.align 4
	.global k68_dispatch
k68_dispatch:
	lsr	r0,r14,1
	and	r0,r0,K68_JTMASK
	add3	r0,k68_jtab,r0
	ld	r1,[r0,0]
	ld	r2,[r0,4]
	brne	r1,r14,1f
	j	[r2]
1:	st	r16,[r13,0x54]
	bl.d	k68_translate		; (r14) -> code; may call FAME helpers, keeps r13-r25
	mov	r0,r14
	ld	r16,[r13,0x54]
	j	[r0]

; a block of RAM code whose 68k words changed: translate it again
	.global k68_stale
k68_stale:			; r1 = the old block
	st	r16,[r13,0x54]
	bl.d	k68_retranslate		; (r14, old block) -> new code
	mov	r0,r14
	ld	r16,[r13,0x54]
	j	[r0]

; block exit whose two-entry cache (r1: {pc, code} x 2) missed: look up as
; k68_dispatch, then remember the block in a free (else the second) entry
	.global k68_dispatch_fill
k68_dispatch_fill:
	mov	r24,r1
	lsr	r0,r14,1
	and	r0,r0,K68_JTMASK
	add3	r0,k68_jtab,r0
	ld	r1,[r0,0]
	ld	r2,[r0,4]
	breq	r1,r14,1f
	st	r16,[r13,0x54]
	ld	r25,[k68_flushes]
	bl.d	k68_translate
	mov	r0,r14
	ld	r16,[r13,0x54]
	mov	r2,r0
	ld	r1,[k68_flushes]
	breq	r1,r25,1f
	j	[r2]			; (code cache emptied: the old block is gone)
1:	ld	r3,[r24,0]
	breq	r3,0,2f
	add	r24,r24,8
2:	st	r14,[r24,0]
	j.d	[r2]
	st	r2,[r24,4]

; an instruction done by FAME inside a block: then the block ends. The
; opcode is read again (FAME's idle detector may have patched it)
k68_tfall:
	ldw	r17,[r14,-2]
	st	r14,[r13,0x60]
	st	r15,[r13,0x64]
	st	r16,[r13,0x54]
	st	r17,[r13,0x58]
	bl	k68_flags_out
	ld	r1,[k68_fallbacks]
	add	r1,r1,1
	st	r1,[k68_fallbacks]
	ld	r1,[k68_fametab]
	ld.as	r1,[r1,r17]
	jl.d	[r1]
	sub	r0,r13,0x20
	ld	r14,[r13,0x60]
	ld	r15,[r13,0x64]
	ld	r16,[r13,0x54]
	bl	k68_flags_in
#ifdef K68CHECK
	b	k68_done
#else
	sub.f	r16,r16,0
	ble	k68_done
	b	k68_dispatch
#endif
'''

ENDS = re.compile(r'\tsub\tr15|add\tr14,r14,r0|k68_tfall|k68_exc|k68_addrerr')

def gen_templates():
    import ops68
    emit('\n#ifdef K68JIT\n\t.text\n' + JIT)
    tl = sorted(ops68.templates.items(), key=lambda kv: kv[1])
    fall = len(tl)
    descs = []
    allt = tl + [(('\tj\tk68_tfall', 0), fall)]
    # templates as subroutines (blocks call the big ones: one shared copy
    # keeps the i-cache working set small); return address in r23
    emit('\t.text')
    # (the block sets r17 and steps r14 before "jl sN")
    for (text, ext), i in allt:
        st = re.sub(r'\tTNEXT\t', '\tTNEXTS\t', text)
        emit('\t.align 4\ns%d:\n\tmov\tr23,blink\n%s\n99:' % (i, st))
    emit('\t.section .rodata.k68tpl,"a"\n\t.align 4')
    for (text, ext), i in allt:
        t = re.sub(r'\tTNEXT\t(\S+)$', r'\tTNEXTL\t\1', text)   # the last one falls through
        emit('\t.balign 4\nt%d:\n%s\n99:\nt%d_e:' % (i, t, i))
        descs.append('\t.word t%d, (t%d_e - t%d) | (%d << 16) | (%d << 31) | (%d << 30), %s' % (
            i, i, i, ext, 1 if ENDS.search(text) else 0, 1 if 'r17' in text else 0,
            's%d' % i))
    emit('\t.align 4\n\t.global k68_tdesc\nk68_tdesc:\n' + '\n'.join(descs))
    t7, tt = [], []
    for grp in range(8192):
        v = ops68.ttab.get(grp)
        if isinstance(v, list):
            tt.append(0x8000 | len(t7)); t7 += [fall if x is None else x for x in v]
        else:
            tt.append(fall if v is None else v)
    emit('\t.global k68_ttab\nk68_ttab:')
    for i in range(0, 8192, 16): emit('\t.short ' + ','.join(str(x) for x in tt[i:i + 16]))
    emit('\t.global k68_t7\nk68_t7:')
    for i in range(0, len(t7), 16): emit('\t.short ' + ','.join(str(x) for x in t7[i:i + 16]))
    emit('#endif')
    print('%d templates' % len(descs))

NX = r'''
	.align 4
k68_nx:		; shared NEXT (-DK68TAIL): cycles in r0
#ifdef K68CHECK
	sub	r16,r16,r0
	b	k68_done
#else
	ldw	r17,[r14]
	sub.f	r16,r16,r0
	ble	k68_done
	lsr	r1,r17,3
	ld.as	r1,[r18,r1]
	add	r14,r14,2
	j	[r1]
#endif
'''

def main():
    gen_frame()
    gen_handlers()
    # env K68HOT=1: the handlers listed in hot.txt (most used first, from
    # profile runs) are emitted first, packed together (fewer i-cache lines)
    items = list(handlers.items())
    hf = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.environ.get('K68HOTF') or 'hot.txt')
    if os.environ.get('K68HOT') and os.path.exists(hf):
        rank = {l.strip(): i for i, l in enumerate(open(hf)) if l.strip()}
        items.sort(key=lambda kv: rank.get(kv[1], len(rank)))
    # env K68TAIL=N (-DK68TAIL): handlers outside the N hottest of hot.txt end in
    # a shared NEXT (b.d k68_nx / mov r0,cycles: 8 bytes instead of 28), so the
    # long tail of handlers touches fewer i-cache lines (+1 cycle each)
    tailn = int(os.environ.get('K68TAIL') or -1)
    if tailn >= 0:
        rank = {l.strip(): i for i, l in enumerate(open(hf)) if l.strip()}
        emit(NX)
    import ops68
    for t, lab in ops68.ROUTINES.items():   # -DK68OUT: shared EA routines (hot: used by every tail handler)
        emit('\t.align 4\n%s:\n%s' % (lab, t))
    # env K68SPLIT=N (-DFIXLD): handlers outside the N hottest of the hot list go to .text.k68cold
    # (placed after the fixed hot window by fix.ld)
    splitn = int(os.environ.get('K68SPLIT') or -1)
    hrank = {l.strip(): i for i, l in enumerate(open(hf)) if l.strip()} if splitn >= 0 else {}
    cold = False
    for text, lab in items:
        if splitn >= 0 and not cold and hrank.get(lab, 1 << 30) >= splitn:
            emit('	.section .text.k68cold,"ax",@progbits')
            cold = True
        if tailn >= 0 and rank.get(lab, 1 << 30) >= tailn:
            text = re.sub(r'\tNEXTR?\t(\S+)', r'\tb.d\tk68_nx\n\tmov\tr0,\1', text)
        emit('\t.align 4\n%s:\n%s' % (lab, text))
    emit('\n\t.section .rodata\n\t.align 4\n\t.global k68_table\nk68_table:')
    for i in range(0, 8192, 8):
        if 0xc10 <= i < 0xc20:   # -DK68WL: bra.s back by 9..128 bytes (0x6080-0x60f7) to k68wl.S's stub first
            emit('#ifdef K68WL\n\t.global h_6008\n\t.word ' + ','.join('k68_wl_stub' if j < 0xc1f else table[j] for j in range(i, i + 8)) + '\n#else')
            emit('\t.word ' + ','.join(table[i:i + 8]) + '\n#endif')
            continue
        emit('\t.word ' + ','.join(table[i:i + 8]))
    gen_templates()
    o = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith('-') else 'k68i.S'
    open(o, 'w').write('\n'.join(out) + '\n')
    print('%s: %d handlers, %d groups done' % (o, len(handlers), sum(t != 'k68_fallback' for t in table)))

if __name__ == '__main__':
    main()
