# mkym.py: writes ym/ym_patched.c = PicoDrive's pico/sound/ym2612.c with
# -DYMX changes (run from port/; the build compiles the result):
# - op_calc/op_calc1 read the small tables (sin 512 B + tl2 6.6 KB) instead
#   of the 208 KB ym_tl_tab: ym_tl_tab[(env<<7)|s] == (env*4 + sin[s] >=
#   13*256 ? 0 : tl2[env*4 + sin[s]]) for even env (how init builds it).
# - -DYMLOOP: chan_render_loop is ym/ymloop.c (state in locals).
src = open('../picodrive/pico/sound/ym2612.c').read()
def sub(a, b, n=1):
    global src
    assert src.count(a) == n, (a, src.count(a))
    src = src.replace(a, b)
sub('\tret = ym_tl_tab[sin | (env<<7)];\n',
    '\t{ unsigned p = (env<<2) + ym_sin_tab[sin];\n'
    '\t  ret = p >= 13*TL_RES_LEN ? 0 : ym_tl_tab2[p]; }\n', 2)
sub('static UINT16 ym_sin_tab[256];', 'UINT16 ym_sin_tab[256];')
a = 'static void chan_render_loop(chan_rend_context *ct, s32 *buffer, int length)\n{'
b = '#else\nvoid chan_render_loop(chan_rend_context *ct, s32 *buffer, unsigned short length);'
sub(a, '#ifdef YMLOOP\n#include "ymloop.c"\n#else\n' + a)
sub(b, '#endif /* YMLOOP */\n' + b)
open('ym/ym_patched.c', 'w').write('/* generated by ym/mkym.py from ../picodrive/pico/sound/ym2612.c */\n' + src)

# sn_patched.c (-DSNX): sn76496.c with SN76496Update from ym/snx.c (state in locals)
s = open('../picodrive/pico/sound/sn76496.c').read()
a = 'void SN76496Update(short *buffer, int length, int stereo)\n{'
assert s.count(a) == 1
s = s.replace(a, '#include "snx.c"\n' + a)
open('ym/sn_patched.c', 'w').write('/* generated by ym/mkym.py from ../picodrive/pico/sound/sn76496.c */\n' + s)
